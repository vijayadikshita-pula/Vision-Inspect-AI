def calculate_severity(size_score, location_score, defect_type_score, confidence):
    score = (size_score * 0.30) + (location_score * 0.25) + (defect_type_score * 0.25) + ((confidence * 100) * 0.20)
    score = round(float(score), 2)
    if score >= 80:
        level = "Critical"
    elif score >= 60:
        level = "High"
    elif score >= 40:
        level = "Medium"
    else:
        level = "Low"
    return score, level

